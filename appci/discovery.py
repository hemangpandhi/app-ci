"""Discover production modules, test suites and sources of any app from Soong metadata.

Sources of truth (both generated by every Soong build):
  * out/soong/module_bp_java_deps.json   module_type, srcs, dependencies, jars
  * $PRODUCT_OUT/module-info.json        test suites, test configs, installed files
"""
from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

from . import util
from .aosp import AospTree

PROD_TYPES = {"android_app", "android_library", "java_library", "java_library_static"}
ROBO_TYPES = {"android_robolectric_test"}
DEVICE_TEST_TYPES = {"android_test", "custom_android_test"}
HOST_TEST_TYPES = {"java_test_host", "android_ravenwood_test"}
SUPPORT_TYPES = {"android_test_helper_app", "java_test_helper_library"}


@dataclass
class TestModule:
    name: str
    kind: str                      # robolectric | device | host
    path: str
    instrumentation_for: Optional[str] = None
    test_config: Optional[str] = None


@dataclass
class AppProfile:
    path: str
    name: str
    slug: str
    apps: List[str] = field(default_factory=list)
    libs: List[str] = field(default_factory=list)
    support_modules: List[str] = field(default_factory=list)
    tests: List[TestModule] = field(default_factory=list)
    java_srcs: List[str] = field(default_factory=list)
    kt_srcs: List[str] = field(default_factory=list)
    test_java_srcs: List[str] = field(default_factory=list)
    test_kt_srcs: List[str] = field(default_factory=list)
    module_paths: Dict[str, str] = field(default_factory=dict)

    @property
    def prod_modules(self) -> List[str]:
        return self.apps + self.libs

    def tests_of(self, kind: str) -> List[TestModule]:
        return [t for t in self.tests if t.kind == kind]

    def to_dict(self):
        return asdict(self)

    @classmethod
    def from_dict(cls, d) -> "AppProfile":
        d = dict(d)
        d["tests"] = [TestModule(**t) for t in d.get("tests", [])]
        return cls(**d)


def _under(path: str, root: str) -> bool:
    return path == root or path.startswith(root + "/")


def _app_display_name(path: str, apps: List[str]) -> str:
    if apps:
        return sorted(apps, key=len)[0]
    return Path(path).name


def _app_slug(path: str) -> str:
    p = path.strip("/")
    for prefix in ("packages/apps/", "vendor/", "packages/"):
        if p.startswith(prefix):
            p = p[len(prefix):]
            break
    return util.slug(p)


def discover_app(tree: AospTree, app_path: str, target: str = "device",
                 entry: Optional[dict] = None) -> AppProfile:
    cfg = tree.cfg
    entry = entry or cfg.app_entry(app_path)
    app_path = app_path.strip("/")
    tree.ensure_metadata(target)
    jdeps = tree.jdeps(target)
    minfo = tree.module_info(target)
    test_re = re.compile(cfg["discovery"]["test_module_pattern"])

    forced = set(entry.get("modules") or [])
    excluded = set(entry.get("exclude_modules") or [])
    forced_tests = set(entry.get("tests") or [])
    excluded_tests = set(entry.get("exclude_tests") or [])

    apps, libs, support, tests = [], [], [], []
    module_paths: Dict[str, str] = {}
    for name, info in jdeps.items():
        paths = info.get("path") or []
        if not paths or not _under(paths[0], app_path) or name in excluded:
            continue
        mtype = info.get("module_type") or ""
        suites = set((minfo.get(name) or {}).get("compatibility_suites") or [])
        module_paths[name] = paths[0]
        kind = None
        if mtype in ROBO_TYPES or "robolectric-tests" in suites:
            kind = "robolectric"
        elif mtype in DEVICE_TEST_TYPES:
            kind = "device"
        elif mtype in HOST_TEST_TYPES:
            kind = "host"
        if kind or name in forced_tests:
            if name in excluded_tests:
                continue
            instr = None
            if kind == "robolectric":
                for dep in info.get("dependencies") or []:
                    dinfo = jdeps.get(dep) or {}
                    if dinfo.get("module_type") == "android_app" and _under((dinfo.get("path") or [""])[0], app_path):
                        instr = dep
                        break
            cfgs = (minfo.get(name) or {}).get("test_config") or []
            tests.append(TestModule(name, kind or "device", paths[0], instr, cfgs[0] if cfgs else None))
            continue
        if name in forced:
            (apps if mtype == "android_app" else libs).append(name)
            continue
        if forced:
            # Explicit module list given: everything else in the tree is support code.
            if mtype in PROD_TYPES:
                support.append(name)
            continue
        if mtype in SUPPORT_TYPES or (mtype in PROD_TYPES and test_re.search(name)):
            support.append(name)
        elif mtype == "android_app":
            apps.append(name)
        elif mtype in PROD_TYPES:
            libs.append(name)

    def collect(mods: List[str]):
        java, kt = set(), set()
        for m in mods:
            for s in jdeps.get(m, {}).get("srcs") or []:
                if not _under(s, app_path) or not (tree.root / s).is_file():
                    continue
                (java if s.endswith(".java") else kt if s.endswith(".kt") else set()).add(s)
        return sorted(java), sorted(kt)

    java_srcs, kt_srcs = collect(apps + libs)
    t_java, t_kt = collect([t.name for t in tests] + support)
    prod = set(java_srcs) | set(kt_srcs)
    t_java = [s for s in t_java if s not in prod]
    t_kt = [s for s in t_kt if s not in prod]

    name = entry.get("name") or _app_display_name(app_path, apps)
    return AppProfile(
        path=app_path, name=name, slug=entry.get("slug") or _app_slug(app_path),
        apps=sorted(apps), libs=sorted(libs), support_modules=sorted(support),
        tests=sorted(tests, key=lambda t: (t.kind, t.name)),
        java_srcs=java_srcs, kt_srcs=kt_srcs, test_java_srcs=t_java, test_kt_srcs=t_kt,
        module_paths=module_paths,
    )


def _project_root(root: Path, path: str) -> str:
    """The git project (repo manifest entry) that owns `path`; one app == one git repo."""
    p = Path(path)
    for cand in [p, *p.parents]:
        if str(cand) in ("", "."):
            break
        if (root / cand / ".git").exists():
            return str(cand)
    return path


def scan_apps(tree: AospTree, roots: Optional[List[str]] = None, target: str = "device",
              installed_only: Optional[bool] = None) -> List[Dict[str, object]]:
    """Find every app root (directory owning a production android_app) under `roots`."""
    cfg = tree.cfg
    dcfg = cfg["discovery"]
    roots = [r.strip("/") for r in (roots or dcfg["scan_roots"])]
    installed_only = dcfg["installed_only"] if installed_only is None else installed_only
    excludes = [e.strip("/") for e in dcfg.get("exclude_paths") or []]
    test_re = re.compile(dcfg["test_module_pattern"])
    tree.ensure_metadata(target)
    jdeps = tree.jdeps(target)
    installed = tree.product_packages(target) if installed_only else None

    by_path: Dict[str, List[str]] = {}
    for name, info in jdeps.items():
        if info.get("module_type") != "android_app" or test_re.search(name):
            continue
        path = (info.get("path") or [""])[0]
        if not any(_under(path, r) for r in roots) or any(_under(path, e) for e in excludes):
            continue
        if "/tests" in path or "/test/" in path or path.endswith("/test") or "/samples" in path:
            continue
        by_path.setdefault(_project_root(tree.root, path), []).append(name)

    # Collapse nested app roots into their outermost parent.
    result: Dict[str, List[str]] = {}
    for path in sorted(by_path, key=len):
        parent = next((p for p in result if _under(path, p)), None)
        result.setdefault(parent or path, []).extend(by_path[path])

    apps = []
    for path, mods in sorted(result.items()):
        in_image = sorted(m for m in mods if installed is None or m in installed)
        if installed is not None and not in_image:
            continue
        apps.append({"path": path, "modules": sorted(mods), "in_image": in_image})
    return apps
